-- PostgreSQL schema, equivalent to the SQLite migrations 0001-0012. A new
-- PostgreSQL database starts here; later migrations come in pairs (one
-- file in migrations/, one here) with the same number.

CREATE TABLE settings (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE users (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT NOT NULL UNIQUE,
    created_at   BIGINT NOT NULL,
    email        TEXT NOT NULL DEFAULT '',
    oidc_subject TEXT
);
CREATE UNIQUE INDEX users_oidc_subject ON users(oidc_subject) WHERE oidc_subject IS NOT NULL;

CREATE TABLE preauth_keys (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    prefix     TEXT NOT NULL,
    hash       BYTEA NOT NULL UNIQUE,
    reusable   BOOLEAN NOT NULL DEFAULT FALSE,
    ephemeral  BOOLEAN NOT NULL DEFAULT FALSE,
    used       BOOLEAN NOT NULL DEFAULT FALSE,
    expires_at BIGINT NOT NULL,
    created_at BIGINT NOT NULL
);

CREATE TABLE nodes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name           TEXT NOT NULL UNIQUE,
    machine_key    TEXT NOT NULL UNIQUE,
    ipv4           TEXT NOT NULL UNIQUE,
    ipv6           TEXT NOT NULL UNIQUE,
    os             TEXT NOT NULL DEFAULT '',
    token_hash     BYTEA NOT NULL UNIQUE,
    ephemeral      BOOLEAN NOT NULL DEFAULT FALSE,
    preauth_key_id BIGINT REFERENCES preauth_keys(id) ON DELETE SET NULL,
    created_at     BIGINT NOT NULL,
    last_seen      BIGINT NOT NULL,
    node_key       TEXT NOT NULL DEFAULT '',
    disco_key      TEXT NOT NULL DEFAULT '',
    endpoints      TEXT NOT NULL DEFAULT '[]',
    relay_offered  BOOLEAN NOT NULL DEFAULT FALSE,
    relay_approved BOOLEAN NOT NULL DEFAULT FALSE,
    ssh_host_key   TEXT NOT NULL DEFAULT '',
    os_version     TEXT NOT NULL DEFAULT '',
    client_version TEXT NOT NULL DEFAULT ''
);

CREATE TABLE api_keys (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prefix     TEXT NOT NULL UNIQUE,
    hash       BYTEA NOT NULL UNIQUE,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    last_used  BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE sessions (
    hash       BYTEA PRIMARY KEY,
    identity   TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);

CREATE TABLE routes (
    node_id    BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    prefix     TEXT NOT NULL,
    advertised BOOLEAN NOT NULL DEFAULT TRUE,
    approved   BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (node_id, prefix)
);

CREATE TABLE exposures (
    node_id    BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    name       TEXT NOT NULL UNIQUE,
    port       BIGINT NOT NULL,
    advertised BOOLEAN NOT NULL DEFAULT TRUE,
    approved   BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (node_id, name)
);

CREATE TABLE recordings (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_name  TEXT NOT NULL,
    local_user TEXT NOT NULL,
    src_node   TEXT NOT NULL,
    src_user   TEXT NOT NULL,
    started_at BIGINT NOT NULL,
    ended_at   BIGINT NOT NULL,
    size       BIGINT NOT NULL,
    file       TEXT NOT NULL
);

CREATE TABLE flow_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_name    TEXT NOT NULL,
    proto        BIGINT NOT NULL,
    client       TEXT NOT NULL,
    server       TEXT NOT NULL,
    port         BIGINT NOT NULL,
    outbound     BOOLEAN NOT NULL,
    denied       BOOLEAN NOT NULL,
    started_at   BIGINT NOT NULL,
    ended_at     BIGINT NOT NULL,
    bytes_sent   BIGINT NOT NULL,
    bytes_recv   BIGINT NOT NULL,
    packets_sent BIGINT NOT NULL,
    packets_recv BIGINT NOT NULL
);
CREATE INDEX flow_logs_ended ON flow_logs(ended_at);
CREATE INDEX flow_logs_node ON flow_logs(node_name, ended_at);

CREATE TABLE audit_log (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at        BIGINT NOT NULL,
    actor     TEXT NOT NULL,
    action    TEXT NOT NULL,
    detail    TEXT NOT NULL DEFAULT '',
    prev_hash BYTEA NOT NULL,
    hash      BYTEA NOT NULL
);
CREATE INDEX audit_log_at ON audit_log(at);

CREATE TABLE access_requests (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id      BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    dst          TEXT NOT NULL,
    duration     BIGINT NOT NULL,
    reason       TEXT NOT NULL DEFAULT '',
    status       TEXT NOT NULL,
    requested_at BIGINT NOT NULL,
    decided_by   TEXT NOT NULL DEFAULT '',
    decided_at   BIGINT NOT NULL DEFAULT 0,
    expires_at   BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX access_requests_status ON access_requests(status, expires_at);

CREATE TABLE lock_chain (
    version BIGINT PRIMARY KEY,
    state   BYTEA NOT NULL
);
CREATE TABLE lock_signatures (
    node_key  TEXT PRIMARY KEY,
    signature BYTEA NOT NULL
);

CREATE TABLE servers (
    id         TEXT PRIMARY KEY,
    public_url TEXT NOT NULL,
    relay_url  TEXT NOT NULL,
    quic_addr  TEXT NOT NULL DEFAULT '',
    started_at BIGINT NOT NULL,
    last_seen  BIGINT NOT NULL
);
CREATE TABLE presence (
    node_id   BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    server_id TEXT NOT NULL,
    PRIMARY KEY (node_id, server_id)
);
CREATE TABLE leases (
    name       TEXT PRIMARY KEY,
    holder     TEXT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE TABLE change_seq (
    id  BIGINT PRIMARY KEY,
    seq BIGINT NOT NULL
);
INSERT INTO change_seq(id, seq) VALUES (1, 0);
